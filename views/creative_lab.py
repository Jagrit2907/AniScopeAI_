"""Screen 4 — Creative Opportunity Lab (rules-based, editable concept drafts)."""
import streamlit as st

from components import Shinigami
from components.styles import empty_state, label, page_header
from src import state
from src.concept_builder import build_concept
from src.theme_extraction import ASPECT_TAXONOMY

page_header("Localized offerings", "Creative Opportunity Lab",
            "Turn audience themes into an original concept worth testing — traceable to its evidence, and never presented as validated.")

finding = st.session_state.get("selected_finding")
themes_state = st.session_state.get("selected_themes") or []

cautions, discoveries = [], []
if not finding:
    cautions.append("No audience finding is selected, so any concept here is exploratory, not evidence-led. "
                    "Pick themes in Audience Intelligence to ground it.")
else:
    discoveries.append(f"Grounded in: {finding['summary']}")
Shinigami.speak(cautions, discoveries, "Choose themes and an objective, then build a draft you can edit.")

st.markdown("#### 1 · Inputs")
with st.container(border=True):
    c1, c2 = st.columns(2)
    themes = c1.multiselect("Storytelling themes", list(ASPECT_TAXONOMY),
                            default=[t for t in themes_state if t in ASPECT_TAXONOMY],
                            help="Prefilled from themes you selected in Audience Intelligence.")
    objective = c2.selectbox("Creative objective", ["Original series pitch", "Short-form web series", "Spin-off / side story",
                                                    "Campaign or promotional story", "Community event narrative"])
    insight = st.text_area("Audience insight this concept responds to",
                           value=finding["summary"] if finding else "", height=80,
                           placeholder="e.g. Reviewers praise strategic duels but criticise slow pacing")
    a1, a2 = st.columns(2)
    audience = a1.text_input("Target audience hypothesis", placeholder="e.g. Indian college students who follow strategy anime")
    direction = a2.text_input("Optional setting / direction", placeholder="Leave blank for a generated setting")
    if not themes:
        st.caption("Select at least one theme to build a concept.")
    b1, b2, _ = st.columns([1, 1, 3])
    if b1.button("Build concept", type="primary", disabled=not themes):
        st.session_state["concept_variation"] = 0
        st.session_state["concept"] = build_concept(themes, insight, audience, objective, direction, 0,
                                                    criticised=(finding or {}).get("criticised"))
        state.save_workspace()
    if b2.button("Try another variation", disabled=not themes or not st.session_state.get("concept")):
        st.session_state["concept_variation"] += 1
        st.session_state["concept"] = build_concept(themes, insight, audience, objective, direction,
                                                    st.session_state["concept_variation"],
                                                    criticised=(finding or {}).get("criticised"))
        state.save_workspace()

concept = st.session_state.get("concept")
st.markdown("#### 2 · Evidence trail")
t1, t2, t3 = st.columns(3)
with t1:
    st.markdown(label("observed"), unsafe_allow_html=True)
    st.write(finding["summary"] if finding else "No audience observation selected.")
with t2:
    st.markdown(label("interp"), unsafe_allow_html=True)
    if finding and (finding.get("praised") or finding.get("criticised")):
        st.write(("Emphasise " + ", ".join(finding.get("praised") or ["—"]) + ". ")
                 + ("Design around " + ", ".join(finding["criticised"]) + "." if finding.get("criticised") else ""))
    else:
        st.write("No interpretation without an audience observation.")
with t3:
    st.markdown(label("hyp"), unsafe_allow_html=True)
    st.write(concept["core_premise"] if concept else "No concept built yet.")

st.markdown("#### 3 · Concept draft")
if not concept:
    empty_state("No concept yet", "<p>Choose themes and press <b>Build concept</b>. The draft is generated by transparent "
                "rules (theme → design levers + generic genre building blocks) and is fully editable.</p>")
    st.stop()

with st.container(border=True):
    st.caption(f"{concept['method']} · Variation {concept['variation']} · {concept['validation_status']}")
    edited = dict(concept)
    e1, e2 = st.columns([1, 2])
    edited["working_title"] = e1.text_input("Working title", concept["working_title"])
    edited["core_premise"] = e2.text_area("Core premise", concept["core_premise"], height=68)
    e3, e4 = st.columns(2)
    edited["central_character"] = e3.text_area("Central character", concept["central_character"], height=90)
    edited["main_conflict"] = e4.text_area("Main conflict", concept["main_conflict"], height=90)
    edited["hook"] = st.text_input("Emotional / thematic hook", concept["hook"])
    e5, e6 = st.columns(2)
    edited["strengths_to_emphasise"] = e5.text_area("Strengths to emphasise (one per line)",
                                                    "\n".join(concept["strengths_to_emphasise"]), height=110).splitlines()
    edited["risks_to_avoid"] = e6.text_area("Risks / weaknesses to avoid (one per line)",
                                            "\n".join(concept["risks_to_avoid"]), height=110).splitlines()
    edited["audience_hypothesis"] = st.text_input("Audience hypothesis", concept["audience_hypothesis"])
    st.markdown(f"**Inspired by themes:** {', '.join(concept['inspired_by_themes'])}  ·  **Why explored:** {concept['why_explored']}")
    st.caption("Built from generic genre ingredients — it does not reuse characters, plots or dialogue from existing works, "
               "but it has not been legally reviewed, audience-tested or commercially validated.")
    s1, s2, s3 = st.columns([1, 1, 2])
    if s1.button("Save concept", type="primary"):
        st.session_state["concept"] = edited
        saved = [c for c in st.session_state["saved_concepts"] if c.get("working_title") != edited["working_title"]]
        st.session_state["saved_concepts"] = saved + [edited]
        state.save_workspace()
        st.success("Concept saved to the workspace.")
    if s2.button("Send to Business Planner"):
        st.session_state["concept"] = edited
        state.save_workspace()
        st.switch_page("views/business_planner.py")

if st.session_state.get("saved_concepts"):
    with st.expander(f"Saved concepts ({len(st.session_state['saved_concepts'])})"):
        for i, c in enumerate(st.session_state["saved_concepts"]):
            cc1, cc2 = st.columns([4, 1])
            cc1.markdown(f"**{c['working_title']}** — {c['core_premise']}")
            if cc2.button("Load", key=f"load_c_{i}"):
                st.session_state["concept"] = c
                st.rerun()
